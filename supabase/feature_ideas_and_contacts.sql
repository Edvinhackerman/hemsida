alter table public.profiles
  add column if not exists is_public boolean not null default false;

create table if not exists public.feature_ideas (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  details text not null,
  status text not null default 'open',
  created_at timestamptz not null default now(),
  constraint feature_idea_title_length check (length(trim(title)) between 5 and 100),
  constraint feature_idea_details_length check (length(trim(details)) between 10 and 2000),
  constraint feature_idea_status check (status in ('open', 'planned', 'in_progress', 'done', 'declined'))
);

create table if not exists public.feature_idea_votes (
  idea_id uuid not null references public.feature_ideas(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (idea_id, user_id)
);

create table if not exists public.feature_idea_comments (
  id bigint generated by default as identity primary key,
  idea_id uuid not null references public.feature_ideas(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  constraint feature_idea_comment_length check (length(trim(body)) between 2 and 1000)
);

create index if not exists feature_ideas_created_at_idx
  on public.feature_ideas (created_at desc);
create index if not exists feature_ideas_user_created_at_idx
  on public.feature_ideas (user_id, created_at desc);
create index if not exists feature_idea_comments_idea_created_idx
  on public.feature_idea_comments (idea_id, created_at);
create index if not exists feature_idea_comments_user_created_at_idx
  on public.feature_idea_comments (user_id, created_at desc);

alter table public.feature_ideas enable row level security;
alter table public.feature_idea_votes enable row level security;
alter table public.feature_idea_comments enable row level security;

revoke all on table public.feature_ideas, public.feature_idea_votes, public.feature_idea_comments
  from public, anon, authenticated;

create or replace function public.get_feature_ideas()
returns table (
  idea_id uuid,
  title text,
  details text,
  status text,
  created_at timestamptz,
  author_name text,
  vote_count bigint,
  comment_count bigint,
  has_voted boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    idea.id,
    idea.title,
    idea.details,
    idea.status,
    idea.created_at,
    case when profile.is_public then coalesce(nullif(profile.display_name, ''), 'Badare') else 'Badare' end,
    (select count(*) from public.feature_idea_votes as vote where vote.idea_id = idea.id),
    (select count(*) from public.feature_idea_comments as comment where comment.idea_id = idea.id),
    auth.uid() is not null and exists (
      select 1 from public.feature_idea_votes as vote
      where vote.idea_id = idea.id and vote.user_id = auth.uid()
    )
  from public.feature_ideas as idea
  left join public.profiles as profile on profile.user_id = idea.user_id
  where idea.status <> 'declined' or public.is_site_admin()
  order by
    case idea.status when 'open' then 0 when 'planned' then 1 when 'in_progress' then 2 when 'done' then 3 else 4 end,
    idea.created_at desc;
$$;

create or replace function public.get_feature_idea_comments(p_idea_id uuid)
returns table (
  comment_id bigint,
  author_name text,
  body text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    comment.id,
    case when profile.is_public then coalesce(nullif(profile.display_name, ''), 'Badare') else 'Badare' end,
    comment.body,
    comment.created_at
  from public.feature_idea_comments as comment
  left join public.profiles as profile on profile.user_id = comment.user_id
  where comment.idea_id = p_idea_id
    and exists (
      select 1 from public.feature_ideas as idea
      where idea.id = comment.idea_id
        and (idea.status <> 'declined' or public.is_site_admin())
    )
  order by comment.created_at asc;
$$;

create or replace function public.create_feature_idea(p_title text, p_details text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if exists (
    select 1 from public.feature_ideas
    where user_id = auth.uid() and created_at > now() - interval '10 minutes'
  ) then
    raise exception 'Please wait before submitting another idea';
  end if;
  insert into public.feature_ideas (user_id, title, details)
  values (auth.uid(), trim(p_title), trim(p_details));
end;
$$;

create or replace function public.set_feature_idea_vote(p_idea_id uuid, p_is_voted boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if not exists (
    select 1 from public.feature_ideas as idea
    where idea.id = p_idea_id
      and (idea.status <> 'declined' or public.is_site_admin())
  ) then
    raise exception 'Idea not available';
  end if;
  if p_is_voted then
    insert into public.feature_idea_votes (idea_id, user_id)
    values (p_idea_id, auth.uid())
    on conflict (idea_id, user_id) do nothing;
  else
    delete from public.feature_idea_votes
    where idea_id = p_idea_id and user_id = auth.uid();
  end if;
end;
$$;

create or replace function public.add_feature_idea_comment(p_idea_id uuid, p_body text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if exists (
    select 1 from public.feature_idea_comments
    where user_id = auth.uid() and created_at > now() - interval '15 seconds'
  ) then
    raise exception 'Please wait before commenting again';
  end if;
  if not exists (
    select 1 from public.feature_ideas as idea
    where idea.id = p_idea_id
      and (idea.status <> 'declined' or public.is_site_admin())
  ) then
    raise exception 'Idea not available';
  end if;
  insert into public.feature_idea_comments (idea_id, user_id, body)
  values (p_idea_id, auth.uid(), trim(p_body));
end;
$$;

create or replace function public.admin_set_feature_idea_status(p_idea_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_site_admin() then
    raise exception 'Not authorized';
  end if;
  if p_status is null or p_status not in ('open', 'planned', 'in_progress', 'done', 'declined') then
    raise exception 'Invalid status';
  end if;
  update public.feature_ideas set status = p_status where id = p_idea_id;
  if not found then
    raise exception 'Idea not found';
  end if;
end;
$$;

create or replace function public.admin_delete_feature_idea_comment(p_comment_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or not public.is_site_admin() then
    raise exception 'Not authorized';
  end if;
  delete from public.feature_idea_comments where id = p_comment_id;
  if not found then
    raise exception 'Comment not found';
  end if;
end;
$$;

