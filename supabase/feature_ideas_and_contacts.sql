create table if not exists public.municipal_bathplace_contacts (
  place_id bigint primary key references public.places(id) on delete cascade,
  municipality text not null,
  report_url text not null,
  source_url text not null,
  verified_at date,
  constraint municipal_contact_municipality_length check (length(trim(municipality)) between 2 and 120),
  constraint municipal_contact_report_https check (report_url ~ '^https://'),
  constraint municipal_contact_source_https check (source_url ~ '^https://')
);

alter table public.municipal_bathplace_contacts enable row level security;
revoke all on table public.municipal_bathplace_contacts from public, anon, authenticated;
grant select on table public.municipal_bathplace_contacts to anon, authenticated;
grant insert, update, delete on table public.municipal_bathplace_contacts to authenticated;

drop policy if exists "anonymous visitors read verified municipal contacts" on public.municipal_bathplace_contacts;
create policy "anonymous visitors read verified municipal contacts" on public.municipal_bathplace_contacts
  for select to anon using (verified_at is not null);
drop policy if exists "visitors read verified municipal contacts" on public.municipal_bathplace_contacts;
create policy "visitors read verified municipal contacts" on public.municipal_bathplace_contacts
  for select to authenticated using (verified_at is not null or public.is_site_admin());
drop policy if exists "admins manage municipal contacts" on public.municipal_bathplace_contacts;
create policy "admins manage municipal contacts" on public.municipal_bathplace_contacts
  for all to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
